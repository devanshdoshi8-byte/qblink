// Advisory buffers only: never change the token, priority, or estimated wait.
export function shouldReturn(location: WaitingLocation, ahead: number, waitMinutes: number, status: string) {
  if (status !== "waiting" || location === "area") return false;
  return location === "out"
    ? ahead <= 2 || waitMinutes <= 10
    : ahead <= 1 || waitMinutes <= 3;
}

export function nextTicketStage(stage: number) { return (stage + 1) % 3; }

